export function glyph(ch) {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS[" "];
}

const esc = (s) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

/**
 * Text in Punktmatrix-Optik als SVG-String.
 * dot/gap in CSS-Pixeln; off = Farbe der "ausgeschalteten" Punkte (LED-Display), null = unsichtbar.
 */
export function dotText(text, { dot = 3, gap = 1, color = "var(--white)", off = null, cls = "" } = {}) {
  const chars = [...text];
  const pitch = dot + gap;
  const columns = chars.length === 0 ? 0 : chars.length * (W + 1) - 1;
  const width = columns === 0 ? 0 : pitch * columns - gap;
  const height = pitch * H - gap;
  const r = dot / 2;
  let on = "";
  let offDots = "";
  chars.forEach((ch, i) => {
    const g = glyph(ch);
    for (let y = 0; y < H; y++) {
      for (let x = 0; x < W; x++) {
        const c = `<circle cx="${+((i * (W + 1) + x) * pitch + r).toFixed(2)}" cy="${+(y * pitch + r).toFixed(2)}" r="${r}"/>`;
        if (g[y][x] === "#") on += c;
        else if (off) offDots += c;
      }
    }
  });
  return (
    `<svg class="dot ${cls}" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${esc(text)}">` +
    (off ? `<g fill="${off}">${offDots}</g>` : "") +
    `<g fill="${color}">${on}</g></svg>`
  );
}
